const html = document.documentElement;
const body = document.body;
const langToggle = document.querySelector("[data-lang-toggle]");
const themeToggles = [...document.querySelectorAll("[data-theme-toggle]")];
const progress = document.querySelector(".progress");
const header = document.querySelector(".site-header");
const sliderImages = [...document.querySelectorAll(".slider img")];
const galleryButtons = [...document.querySelectorAll("[data-gallery] button")];
const lightbox = document.querySelector("[data-lightbox]");
const lightboxImage = lightbox.querySelector("img");
const lightboxClose = document.querySelector("[data-lightbox-close]");
let currentSlide = 0;
let currentLang = "ar";

function setLanguage(lang) {
  currentLang = lang;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  langToggle.textContent = lang === "ar" ? "EN" : "AR";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (content[lang][key]) node.textContent = content[lang][key];
  });

  updateThemeButton();
}

function updateThemeButton() {
  const key = body.dataset.theme === "day" ? "modeButton" : "modeButtonDay";
  const label = content[currentLang][key];
  document.querySelectorAll("[data-theme-label]").forEach((node) => {
    node.textContent = label;
  });
}

function setSlide(index) {
  currentSlide = (index + sliderImages.length) % sliderImages.length;
  sliderImages.forEach((img, imageIndex) => {
    img.classList.toggle("is-active", imageIndex === currentSlide);
  });
}

function updateScrollUi() {
  const max = document.documentElement.scrollHeight - window.innerHeight;
  const ratio = max > 0 ? window.scrollY / max : 0;
  progress.style.width = `${ratio * 100}%`;
  header.classList.toggle("is-scrolled", window.scrollY > 36);

  const cinema = document.querySelector(".cinema");
  if (cinema) {
    const rect = cinema.getBoundingClientRect();
    const offset = Math.max(-90, Math.min(90, rect.top * -0.08));
    cinema.style.setProperty("--parallax", `${offset}px`);
  }
}

function openLightbox(img) {
  lightboxImage.src = img.src;
  lightboxImage.alt = img.alt;
  lightbox.classList.add("is-open");
  lightbox.setAttribute("aria-hidden", "false");
  body.style.overflow = "hidden";
}

function closeLightbox() {
  lightbox.classList.remove("is-open");
  lightbox.setAttribute("aria-hidden", "true");
  body.style.overflow = "";
}

window.addEventListener("load", () => {
  setTimeout(() => body.classList.remove("is-loading"), 450);
});

langToggle.addEventListener("click", () => {
  setLanguage(currentLang === "ar" ? "en" : "ar");
});

themeToggles.forEach((toggle) => {
  toggle.addEventListener("click", () => {
    body.dataset.theme = body.dataset.theme === "day" ? "night" : "day";
    updateThemeButton();
  });
});

document.querySelector("[data-gallery-next]").addEventListener("click", () => setSlide(currentSlide + 1));
document.querySelector("[data-gallery-prev]").addEventListener("click", () => setSlide(currentSlide - 1));

setInterval(() => setSlide(currentSlide + 1), 4200);
setSlide(0);

galleryButtons.forEach((button) => {
  button.addEventListener("click", () => openLightbox(button.querySelector("img")));
});

lightboxClose.addEventListener("click", closeLightbox);
lightbox.addEventListener("click", (event) => {
  if (event.target === lightbox) closeLightbox();
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeLightbox();
});

let touchStartX = 0;
document.querySelector(".slider").addEventListener("touchstart", (event) => {
  touchStartX = event.touches[0].clientX;
}, { passive: true });

document.querySelector(".slider").addEventListener("touchend", (event) => {
  const diff = touchStartX - event.changedTouches[0].clientX;
  if (Math.abs(diff) > 40) setSlide(currentSlide + (diff > 0 ? 1 : -1));
}, { passive: true });

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) entry.target.classList.add("is-visible");
  });
}, { threshold: 0.16 });

document.querySelectorAll(".section-observe").forEach((section) => observer.observe(section));
window.addEventListener("scroll", updateScrollUi, { passive: true });
updateScrollUi();
setLanguage("ar");
